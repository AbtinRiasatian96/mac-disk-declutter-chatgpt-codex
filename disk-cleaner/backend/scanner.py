from .config import Settings

CATEGORY_LABELS = {
    "safe": "🟢 Safe",
    "review": "🟡 Review",
    "personal": "🔵 Personal",
}


def scan(settings: Settings) -> List[Dict[str, str]]:
    targets = _build_targets(settings)
    items = []
    for target in targets:
        path = os.path.expanduser(target["path"])
        if target.get("resolve") == "brew":
            path = _brew_cache_path()
        if not path or not os.path.exists(path):
            continue
        size = _get_size_bytes(path)
        metadata = {
            **target,
            "path": path,
            "size_bytes": size,
            "size_human": _format_bytes(size),
            "category_label": CATEGORY_LABELS.get(target["category"], target["category"]),
        }
        if target.get("include_age"):
            metadata.update(_age_metadata(path))
        if target.get("include_dates"):
            metadata.update(_backup_dates(path))
        items.append(metadata)
    items.extend(_find_orphaned_app_support())
    return items


