def _get_size_bytes(path: str) -> int:
    if os.path.isfile(path):
        return os.path.getsize(path)
    total = 0
    for root, _, files in os.walk(path):
        for name in files:
            try:
                total += os.path.getsize(os.path.join(root, name))
            except OSError:
                continue
    return total


def _format_bytes(size: int) -> str:
    units = ["B", "KB", "MB", "GB", "TB"]
    value = float(size)
    for unit in units:
        if value < 1024 or unit == units[-1]:
            return f"{value:.1f} {unit}"
        value /= 1024
    return f"{value:.1f} TB"


def _brew_cache_path() -> str:
    try:
        result = subprocess.run(["brew", "--cache"], capture_output=True, text=True, check=True)
        return result.stdout.strip()
    except (subprocess.SubprocessError, FileNotFoundError):
        return ""


def _age_metadata(path: str) -> Dict[str, str]:
    timestamps = []
    for root, _, files in os.walk(path):
        for name in files:
            try:
                timestamps.append(os.path.getmtime(os.path.join(root, name)))
            except OSError:
                continue
    if not timestamps:
        return {"age_summary": "No files found."}
    oldest = datetime.fromtimestamp(min(timestamps)).strftime("%Y-%m-%d")
    newest = datetime.fromtimestamp(max(timestamps)).strftime("%Y-%m-%d")
    return {"age_summary": f"Oldest: {oldest}, newest: {newest}"}


def _backup_dates(path: str) -> Dict[str, str]:
    dates = []
    if os.path.isdir(path):
        for name in os.listdir(path):
            full = os.path.join(path, name)
            if os.path.isdir(full):
                dates.append(datetime.fromtimestamp(os.path.getmtime(full)).strftime("%Y-%m-%d"))
    if not dates:
        return {"backup_dates": "No backups detected."}
    return {"backup_dates": ", ".join(sorted(dates)[:5])}


def _find_orphaned_app_support() -> List[Dict[str, str]]:
    support_path = os.path.expanduser("~/Library/Application Support")
    if not os.path.isdir(support_path):
        return []
    app_dirs = {name.lower() for name in os.listdir("/Applications") if name.endswith(".app")}
    items = []
    for name in os.listdir(support_path):
        path = os.path.join(support_path, name)
        if not os.path.isdir(path):
            continue
        if f"{name.lower()}.app" in app_dirs:
            continue
        size = _get_size_bytes(path)
        items.append(
            {
                "name": f"Orphaned support: {name}",
                "path": path,
                "category": "review",
                "default_explanation": "App support folder without a matching installed app.",
                "default_consequence": "App data may be removed if the app is reinstalled.",
                "size_bytes": size,
                "size_human": _format_bytes(size),
                "category_label": CATEGORY_LABELS["review"],
            }
        )
    return items
